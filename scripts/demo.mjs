import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import assert from 'node:assert/strict';
import { execFile } from 'node:child_process';
import { promisify } from 'node:util';
import { serve,request } from '../dist/packages/daemon/src/index.js';
import { Outbox } from '../dist/packages/adapter-sdk/src/index.js';
const exec=promisify(execFile);
const directory=fs.mkdtempSync(path.join(os.tmpdir(),'hyperweave-demo-'));
const root=path.join(directory,'workspace');fs.mkdirSync(root);
fs.writeFileSync(path.join(root,'hello.txt'),'Bonjour\r\n');fs.writeFileSync(path.join(root,'binary.bin'),Buffer.from([0,255,42]));
const archive=path.join(directory,'archive');const daemon=await serve(archive);
const cli=async(...args)=>JSON.parse((await exec(process.execPath,['dist/packages/cli/src/index.js',...args,'--archive',archive,'--json'])).stdout).result;
let box;
try{
 const project=await cli('init','--name','Synthetic demo','--root',root);
 const workspace=await cli('workspace','add','--project',project.id,'--root',root);
 const session=await cli('session','start','--workspace',workspace.id,'--producer','synthetic');
 const coverage=await cli('coverage','--workspace',workspace.id);assert.equal(coverage.entries.length,2);
 const v0=await cli('checkpoint','create','--workspace',workspace.id,'--mode','strict','--operation','demo-v0');
 box=new Outbox(path.join(directory,'outbox.sqlite'),'synthetic');
 box.enqueue({session_id:session.id,type:'message.recorded',causal_parents:[],payload:{role:'user',content:'Modifier les deux fichiers et vérifier le résultat.'}});
 box.enqueue({session_id:session.id,type:'tool.started',causal_parents:[],payload:{action_id:'synthetic-test',before_checkpoint_id:v0.id}});
 await box.flush(events=>request(archive,'appendEvents',{events}));
 fs.writeFileSync(path.join(root,'hello.txt'),'Bonjour HyperWeave\n');fs.writeFileSync(path.join(root,'binary.bin'),Buffer.from([0,255,43]));
 assert.equal(fs.readFileSync(path.join(root,'hello.txt'),'utf8'),'Bonjour HyperWeave\n');
 assert.deepEqual(fs.readFileSync(path.join(root,'binary.bin')),Buffer.from([0,255,43]));
 const outputFile=path.join(directory,'synthetic-output.txt');fs.writeFileSync(outputFile,'Synthetic byte assertions passed\n'+'fixture output\n'.repeat(20_000));
 const attachment=await cli('attachment','add','--input',outputFile,'--type','text/plain');
 const completed=box.enqueue({session_id:session.id,type:'tool.completed',causal_parents:[],payload:{action_id:'synthetic-test',attachments:[attachment.hash],attribution:'explicit'}});
 await box.flush(events=>request(archive,'appendEvents',{events}));
 const v1=await cli('checkpoint','create','--workspace',workspace.id,'--mode','strict','--operation','demo-v1');
 assert.equal((await cli('operation','get','--operation','demo-v1')).result.id,v1.id);
 assert.equal((await cli('action','get','--session',session.id,'--action','synthetic-test')).status,'completed');
 assert.equal((await cli('search','--query','Synthetic byte assertions passed')).length,1);
 await cli('provenance','add','--event',completed.id,'--checkpoint',v1.id,'--path','binary.bin','--relation','observed-result','--method','synthetic byte assertion','--certainty','explicit');
 const diff=await cli('diff','--before',v0.id,'--after',v1.id);assert.equal(diff.length,2);
 const target=path.join(directory,'variant');await cli('materialize','--checkpoint',v0.id,'--target',target);
 assert.equal(fs.readFileSync(path.join(target,'hello.txt'),'utf8'),'Bonjour\r\n');assert.deepEqual(fs.readFileSync(path.join(target,'binary.bin')),Buffer.from([0,255,42]));
 const fork=await cli('timeline','fork','--checkpoint',v0.id);
 const variant=await cli('workspace','add','--project',project.id,'--root',target);
 await cli('timeline','bind','--timeline',fork.id,'--workspace',variant.id);
 const variantSession=await cli('session','start','--workspace',variant.id,'--producer','synthetic-variant');
 fs.writeFileSync(path.join(target,'hello.txt'),'Variante indépendante\n');
 const variantCheckpoint=await cli('checkpoint','create','--workspace',variant.id,'--timeline',fork.id,'--mode','strict');
 const context=await cli('context','build','--checkpoint',variantCheckpoint.id,'--budget','4096');
 assert.equal(context.events.length,0,'Messages from the abandoned trajectory must not leak');
 const file=path.join(directory,'export.json');await cli('export','--target',file);
 const imported=path.join(directory,'imported');
 const result=JSON.parse((await exec(process.execPath,['dist/packages/cli/src/index.js','import','--source',file,'--archive',imported,'--offline','--json'])).stdout).result;assert.equal(result.ok,true);
 const restored=path.join(directory,'imported-v0');await exec(process.execPath,['dist/packages/cli/src/index.js','materialize','--checkpoint',v0.id,'--target',restored,'--archive',imported,'--offline']);
 assert.deepEqual(fs.readFileSync(path.join(restored,'binary.bin')),Buffer.from([0,255,42]));
 await cli('backup','--target',path.join(directory,'backup.sqlite'));
 const verify=await cli('verify');assert.equal(verify.ok,true);
 console.log(JSON.stringify({ok:true,directory,v0:v0.id,v1:v1.id,variant:variantCheckpoint.id,variant_session:variantSession.id,diff,verified:verify.counts},null,2));
}finally{box?.close();await daemon.close();}
